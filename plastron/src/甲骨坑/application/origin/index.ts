// ── vnodePath — the xpath subset =append targets (pure; Tier-A tested) ──────
// Supported: /tag, //tag (any depth), * wildcard, [n] 1-based index,
// [@id='x'], [@class='x'] (class-contains). Steps compose: //div[@id='a']/ul[2]
interface VNLike { type?: string; tag?: string; attrs?: Record<string, unknown>; children?: unknown[] }
interface PathStep { axis: "child" | "desc"; tag: string; id?: string; cls?: string; idx?: number }
const parseXPath = (xpath: string): PathStep[] | null => {
  const steps: PathStep[] = [];
  let rest = String(xpath ?? "").trim();
  if (!rest.startsWith("/")) return null;
  while (rest.length) {
    let axis: "child" | "desc" = "child";
    if (rest.startsWith("//")) { axis = "desc"; rest = rest.slice(2); }
    else if (rest.startsWith("/")) rest = rest.slice(1);
    const m = /^([^/]+)/.exec(rest);
    if (!m) break;
    rest = rest.slice(m[1]!.length);
    const raw = m[1]!;
    const tagM = /^(\*|[a-zA-Z][\w-]*)/.exec(raw);
    const step: PathStep = { axis, tag: tagM?.[1] ?? "*" };
    for (const pm of raw.matchAll(/\[([^\]]+)\]/g)) {
      const p = pm[1]!.trim();
      const attr = /^@(id|class)\s*=\s*['"]([^'"]*)['"]$/.exec(p);
      if (attr) { if (attr[1] === "id") step.id = attr[2]; else step.cls = attr[2]; }
      else if (/^\d+$/.test(p)) step.idx = Number(p);
    }
    steps.push(step);
  }
  return steps.length ? steps : null;
};
const stepHit = (n: VNLike, s: PathStep): boolean =>
  !!n && n.type === "el" &&
  (s.tag === "*" || n.tag === s.tag) &&
  (s.id === undefined || String(n.attrs?.id ?? "") === s.id) &&
  (s.cls === undefined || String(n.attrs?.class ?? "").split(/\s+/).includes(s.cls));
const descendants = (n: VNLike, out: VNLike[] = []): VNLike[] => {
  for (const ch of (n?.children ?? []) as VNLike[]) { if (ch?.type === "el") { out.push(ch); descendants(ch, out); } }
  return out;
};
/** vnodePath(root, xpath) — the first vnode matching the xpath subset, or null. */
export const vnodePath = (root: unknown, xpath: string): VNLike | null => {
  const steps = parseXPath(xpath);
  if (!steps || !root || (root as VNLike).type !== "el") return null;
  let current: VNLike[] = [root as VNLike];
  for (const s of steps) {
    const pool: VNLike[] = [];
    for (const n of current) {
      const cands = s.axis === "desc" ? descendants(n) : ((n.children ?? []) as VNLike[]);
      for (const c of cands) if (stepHit(c, s)) pool.push(c);
    }
    current = s.idx !== undefined ? (pool[s.idx - 1] ? [pool[s.idx - 1]!] : []) : pool;
    if (current.length === 0) return null;
  }
  return current[0] ?? null;
};
/** deep clone-filter: the tree without this authoring cell's slot. */
const withoutSlot = (n: VNLike, slotKey: string): VNLike => {
  if (!n || n.type !== "el" || !Array.isArray(n.children)) return n;
  const kids = (n.children as VNLike[])
    .filter((ch) => (ch as { attrs?: Record<string, unknown> })?.attrs?.["data-cel"] !== slotKey)
    .map((ch) => withoutSlot(ch, slotKey));
  return { ...n, children: kids };
};
