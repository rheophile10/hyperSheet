  ({ originHelp: { segment: segment === undefined ? "" : String(segment), mode: mode === undefined ? "" : String(mode) } });

// the "(args) - prose" description convention, split into signature + blurb
// (the same regex =inspect uses).
const sigSplit = (desc: string): { sig?: string; blurb: string } => {
  const m = /^\s*(\([^)]*\))\s*[-—:]?\s*([\s\S]*)$/.exec(desc);
  return m ? { sig: m[1], blurb: m[2] ?? "" } : { blurb: desc };
};

// buildHelpIndex(state) — the whole vocabulary as ONE data value (help.index):
// [{name, role, count, blurb, cels: [{key, kind, sig, blurb}]}] grouped by
// role then name. The tree + search render from this reactively; building it
// is one cheap scan.
const buildHelpIndex = (state: State): Array<Record<string, unknown>> => {
  const segMap = (state as { segments?: Map<string, { name: string; role?: string; description?: string }> }).segments;
  const bySeg = new Map<string, Array<{ key: string; kind: string; sig?: string; blurb: string; example?: string; commentary?: string }>>();
  for (const [k, c] of state.cels) {
    const seg = String((c.metadata as { segment?: string }).segment ?? "");
    let kind = "";
    // Dotted keys are skipped only for DATA cels (g.A1, fg.g1.pos) — dotted
    // CALLABLES (window.close, sheetapp.save, fg.set) are vocabulary and were
    // previously invisible to =help entirely (~⅔ of the catalog).
    if (c.celType === "LockedLambdaCel") { if ((c as { _fn?: unknown })._fn === undefined) continue; kind = "locked"; }
    else if (c.celType === "EditableLambdaCel") kind = "editable";
    else if (c.celType === "CompilerCel") kind = "compiler";
    else if (c.celType === "FormulaCel") { if (k.includes(".")) continue; kind = "formula"; }
    else if (c.celType === "ValueCel") { if (k.includes(".") || c.v === "" || c.v === undefined || c.v === null) continue; kind = "value"; }
    else continue;
    const { sig, blurb } = sigSplit(String((c.metadata as { description?: string }).description ?? ""));
    const example = String((c.metadata as { example?: string }).example ?? "");
    const commentary = String((c.metadata as { commentary?: string }).commentary ?? "");
    (bySeg.get(seg) ?? bySeg.set(seg, []).get(seg)!).push({ key: k, kind, sig, blurb: blurb.slice(0, 160), ...(example ? { example } : {}), ...(commentary ? { commentary } : {}) });
  }
  const roleRank: Record<string, number> = { kernel: 0, library: 1, application: 2, user: 3 };
  const out: Array<Record<string, unknown>> = [];
  for (const [nm, m] of segMap ?? []) {
    const cels = (bySeg.get(nm) ?? []).sort((a, b) => a.key.localeCompare(b.key));
    if (!cels.length) continue;                      // only segments with visible vocabulary
    out.push({ name: nm, role: String(m.role ?? "library"), count: cels.length, blurb: String(m.description ?? "").slice(0, 160), cels });
  }
  out.sort((a, b) => (roleRank[String(a.role)] ?? 9) - (roleRank[String(b.role)] ?? 9) || String(a.name).localeCompare(String(b.name)));
  return out;
};

// help.selectNode(state, key) — a function-row / search-hit click: land the
// cel's (or segment's) metadata in help.selectedInfo (handlers have state;
// the pane render stays pure), then the house repaint cycle (mount-headed
// frames suppress value-change propagation). Drains are TARGETED — draining
// "all" here re-entered the effects drain via re-fired =help cells and
// looped.
const helpRepaint = async (state: State): Promise<void> => {
  await (resolveFn(state, "runCycle") as Fn)(state);
  await (resolveFn(state, "drain") as Fn)(state, "origin.effects");   // land re-fired generative tokens
  await (resolveFn(state, "drain") as Fn)(state, "dom.paint");
};
const helpSelectNode: Fn = async (state: State, nodeKey?: unknown) => {
  const k = String(nodeKey ?? "");
  const c = state.cels.get(k);
  const seg = (state as { segments?: Map<string, { description?: string; role?: string; dependencies?: string[] }> }).segments?.get(k);
  const info = c
    ? (() => {
        const cg = (callGraph as { verbs?: Record<string, { calls?: Array<{ to: string }>; calledBy?: string[] }> }).verbs?.[k];
        return { key: k, celType: c.celType, segment: String((c.metadata as { segment?: string }).segment ?? ""), kind: String((c.metadata as { kind?: string }).kind ?? ""), description: String((c.metadata as { description?: string }).description ?? "(no description)"), example: (c.metadata as { example?: string }).example, commentary: (c.metadata as { commentary?: string }).commentary, calls: [...new Set((cg?.calls ?? []).map((e) => e.to))], calledBy: cg?.calledBy ?? [], f: (c as { f?: string }).f };
      })()
    : seg
      // segment node: dependencies as DATA (deps) — the pane renders them as
      // clickable chips (verbLinkRow re-selects the segment), not an f string.
      ? { key: k, celType: "segment", segment: k, kind: String(seg.role ?? "segment"), description: String(seg.description ?? "(no description)"), deps: seg.dependencies ?? [] }
      : { key: k, celType: "?", segment: "", kind: "", description: "(no such cel)" };
  await (resolveFn(state, "setValueBatch") as Fn)(state, [["help.selected", k], ["help.selectedInfo", info]]);
  await helpRepaint(state);
  return null;
};

// help.toggle(state, segName) — the tree's folder click: expand/collapse the
// segment (help.open is the expanded-set) and show its description.
const helpToggle: Fn = async (state: State, segName?: unknown) => {
  const nm = String(segName ?? "");
  if (!nm) return null;
  const open = new Set((state.cels.get("help.open")?.v as string[] | undefined) ?? []);
  if (open.has(nm)) open.delete(nm); else open.add(nm);
  const seg = (state as { segments?: Map<string, { description?: string; role?: string; dependencies?: string[] }> }).segments?.get(nm);
  const info = seg ? { key: nm, celType: "segment", segment: nm, kind: String(seg.role ?? "segment"), description: String(seg.description ?? "(no description)"), deps: seg.dependencies ?? [] } : undefined;
  await (resolveFn(state, "setValueBatch") as Fn)(state, [["help.open", [...open]], ...(info ? [["help.selected", nm], ["help.selectedInfo", info]] as Array<[string, unknown]> : [])]);
  await helpRepaint(state);
  return null;
};

