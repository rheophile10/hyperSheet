// ── INSTALL + boot (origin-application machinery) ───────────────────────────
// The desktop and every app is an origin-application SEGMENT. Three tiers keep
// persist, load, and render separate (the user's "save/load shouldn't auto-add
// to state" concern): origin.install persists an archive to the store (OPFS
// only), origin.launch hydrates it into state on demand, boot.run sequences the
// two. (NB: named origin.install — winapps owns app.assets, the asset fetcher.)

interface DumpedArchive {
  segments?: Array<{ name?: string; cels?: unknown[] }>;
  manifests?: Array<{ name?: string; version?: string; dependencies?: string[]; role?: string }>;
  formatVersion?: number;
}

// origin.install(archive) — persist a segment ARCHIVE (dumpSegments shape:
// {segments,manifests}) into the OPFS segment-store WITHOUT loading it into
// state. store.put/get already split persist from load; this just composes them
// over a dumped archive via store.putRaw (per segment). Idempotent at NAME
// granularity — an already-stored app is skipped, so re-boot is cheap (a real
// version bump is an explicit store.delete + reinstall, not this path). The ONLY
// way a cel reaches state.cels is a later origin.launch (hydrate-closure);
// install never hydrates. Accepts an archive object or its JSON string.
const appInstall: Fn = (async (state: State, archiveArg?: unknown, forceArg?: unknown): Promise<string> => {
  await ensureSegments(state, ["segment-store"]);
  const problems = validateArchive(archiveArg as string | unknown);
  if (problems.length) {
    throw new Error(`origin.install: incomplete archive — ${problems.map((p) => `${p.where}: ${p.message}`).join("; ")}`);
  }
  const arch = (typeof archiveArg === "string" ? JSON.parse(archiveArg) : archiveArg) as DumpedArchive;
  const segments = arch.segments ?? [];
  const manifests = new Map((arch.manifests ?? []).map((m) => [String(m.name), m]));
  const putRaw = resolveFn(state, "store.putRaw") as Fn;
  const readIndex = resolveFn(state, "store.readIndex") as Fn;
  const idx = await (readIndex(state) as Promise<{ segments: Record<string, { versions?: string[] }> }>);
  const force = forceArg === true;
  const installed: string[] = [], skipped: string[] = [];
  for (const s of segments) {
    const name = String(s.name);
    const man = manifests.get(name) ?? { name, version: "0.0.0", description: "installed application segment", dependencies: [], role: "application" };
    const version = String(man.version ?? "0.0.0");
    // VERSION-aware, not name-aware: a returning profile picks up a bumped
    // baked archive on boot (upgrade); the same version re-installs only under
    // force (factory refresh — re-put flips `latest` back to the baked build).
    // Segment names not in the archive — user-created docs — are never touched.
    if (!force && (idx.segments[name]?.versions ?? []).includes(version)) { skipped.push(name); continue; }
    await putRaw(state, name, version, man, { name, cels: s.cels ?? [] });
    installed.push(name);
  }
  return `origin.install — installed: [${installed.join(", ")}]${skipped.length ? `; skipped: [${skipped.join(", ")}]` : ""}`;
}) as Fn;

// installBakedApps — first-run install of the baked APPLICATION + document
// segments: read the inert #plastron-apps manifest the bundle baked into the page
// (a { "<name>": <archive> } map) and origin.install each entry. Touches OPFS
// only, never state. Pass `manifest` to bypass the DOM read (tests / headless).
// No-op off-DOM or without a filesystem backend. A broken baked app must not brick
// boot — failures are logged, not thrown.
const installBakedApps: Fn = (async (state: State, manifestArg?: unknown, forceArg?: unknown): Promise<string[]> => {
  const backend = state.cels.get("file-store.backend")?.v;
  if (backend === "none" || backend === undefined) return [];
  let manifest = manifestArg as Record<string, unknown> | undefined;
  if (manifest === undefined) {
    const g = globalThis as { document?: { getElementById?: (id: string) => { textContent?: string | null } | null } };
    const raw = g.document?.getElementById?.("plastron-apps")?.textContent;
    if (!raw) return [];
    try { manifest = JSON.parse(raw) as Record<string, unknown>; } catch { return []; }
  }
  const installed: string[] = [];
  for (const [appName, archive] of Object.entries(manifest)) {
    try { await (appInstall as Fn)(state, archive, forceArg === true); installed.push(appName); }
    catch (e) { console.warn(`installBakedApps: "${appName}" failed to install`, e); }
  }
  return installed;
}) as Fn;

// refreshApps() — factory-refresh the BAKED set: re-install every archive the
// page shipped with (apps + demo docs), flipping each baked segment's `latest`
// back to the shipped build. User-CREATED segments are untouched (only names
// in the baked manifest are written); a user's saved EDITS of a baked doc are
// shadowed (the prior version stays in the store's versions[], not deleted).
// Reload the page afterwards for boot-hydrated segments (the desktop) to show.
const refreshApps: Fn = (async (state: State): Promise<string> => {
  const confirm = (globalThis as { confirm?: (m: string) => boolean }).confirm;
  if (typeof confirm === "function" && !confirm("Refresh all baked apps/docs to the shipped build? Your own segments are untouched; edits to shipped demo docs revert.")) return "(refresh cancelled)";
  const names = await ((installBakedApps as Fn)(state, undefined, true) as Promise<string[]>);
  return names.length ? `refreshed ${names.length} baked segments: ${names.join(", ")} — reload the page to re-hydrate the desktop` : "(no baked manifest on this page)";
}) as Fn;

// ── update notices ───────────────────────────────────────────────────────────
