// window geometry a genesis declared (cels(…, geom(x,y,w,h[,minW,minH]))) → the
// gen-2 window state cel win.<seg>.state. `key` holds the genesis result {…, geoms}.
// A value in (0,1] is a PROPORTION of the viewport (x/w of viewport.w, y/h of
// viewport.h); >1 is absolute pixels. Applied ONCE per window (a `geomDeclared`
// marker on the state preserves a user's later drag/resize across re-open). Shared
// by origin.run AND the navOpen "=formula" launcher (both spawn geom-bearing windows).
// (Replaces the gen-1 win.geom map sheetView used to read.)
const applyDeclaredGeom = async (state: State, key: string): Promise<void> => {
  const declared = (state.cels.get(key)?.v as { geoms?: Record<string, WGeom> } | undefined)?.geoms;
  if (!declared || !Object.keys(declared).length) return;
  const vw = Number(state.cels.get("viewport.w")?.v) || 1200, vh = Number(state.cels.get("viewport.h")?.v) || 800;
  const px = (v: number | undefined, dim: number): number | undefined => v == null ? undefined : (v > 0 && v <= 1 ? Math.round(v * dim) : v);
  const setValue = resolveFn(state, "setValue") as Fn;
  for (const [seg, g] of Object.entries(declared)) {
    const sref = `win.${seg}.state`;
    const st = state.cels.get(sref)?.v as (Record<string, unknown> & { geomDeclared?: boolean }) | undefined;
    if (!st || typeof st !== "object" || st.geomDeclared) continue;   // un-moved-once gate
    const patch: Record<string, unknown> = { geomDeclared: true };
    if (g.x != null) patch.x = px(g.x, vw); if (g.y != null) patch.y = px(g.y, vh);
    if (g.w != null) patch.w = px(g.w, vw); if (g.h != null) patch.h = px(g.h, vh);
    if (g.minW != null) patch.minW = px(g.minW, vw); if (g.minH != null) patch.minH = px(g.minH, vh);
    await setValue(state, sref, { ...st, ...patch });
  }
};

/** commit (origin.run) — run a cell: set its content from the draft and
 *  re-evaluate. Every cell (元 included) executes its formula/value like A1. 元
 *  is un-deletable: clearing it restores the readme. A structure formula
 *  (=grid …) makes more cels; the post-drain rebuild adds them.
 *  Optional `source`: seed 元.draft with it first, so a caller can run a given
 *  formula into `key` in one call (subsumes the setValue(元.draft)+run pattern). */
const commit: Fn = async (state: State, payload?: unknown, source?: unknown) => {
  const key = typeof payload === "string" ? payload : "元";
  if (source !== undefined) await (resolveFn(state, "setValue") as Fn)(state, "元.draft", String(source));
  const draft = String(state.cels.get("元.draft")?.v ?? "").trim();
  const setCel = resolveFn(state, "setCel") as Fn;

  const src = key === "元" && draft === "" ? README : draft;
  const spec = src === "" ? { celType: "ValueCel", v: "" } : sniff(src);
  const existed = state.cels.has(key);   // sparse: a commit may BIRTH the cel
  // Carry forward ownership/name stamps so editing a GRID cell keeps it
  // owned by its generator (else the sweep can't reclaim it, and the
  // grid never goes away). A1's own segment/name pass through too.
  const prior = state.cels.get(key)?.metadata as
    { segment?: string; name?: string; generatedBy?: Key; definedBy?: Key; origin?: Key } | undefined;
  const md: Record<string, unknown> = { segment: prior?.segment ?? "origin" };
  if (prior?.name) md.name = prior.name;
  if (prior?.generatedBy) md.generatedBy = prior.generatedBy;
  if (prior?.definedBy) md.definedBy = prior.definedBy;
  if (prior?.origin) md.origin = prior.origin;
  if (spec.parser) md.parser = spec.parser;
  // SPARSE birth: committing into an empty grid address creates the cel NOW —
  // it must join its sheet's segment and inherit the GENERATOR stamps the old
  // eager blanks carried (from the sheet's `<seg>.dims` cel, which genesis
  // stamped), else the sweep can never reclaim it and ownership pins break.
  const bornAddr = !existed && key.includes(".") && /^[A-Z]+\d+$/.test(key.slice(key.indexOf(".") + 1));
  if (bornAddr) {
    const segKey = key.slice(0, key.indexOf("."));
    md.segment = segKey;
    md.name = key.slice(key.indexOf(".") + 1);
    const dimsMd = state.cels.get(`${segKey}.dims`)?.metadata as { generatedBy?: Key; definedBy?: Key; origin?: Key } | undefined;
    if (dimsMd?.generatedBy) md.generatedBy = dimsMd.generatedBy;
    if (dimsMd?.definedBy) md.definedBy = dimsMd.definedBy;
    if (dimsMd?.origin) md.origin = dimsMd.origin;
  }

  // Collaborative / encrypted sheets route the edit through the CRDT change
  // pipeline (sheetsync.commit) instead of a plain setCel: gate the author
  // (writableBy), record a SIGNED op on the segment's grow-only diff-stack, fold
  // it back to the source cel, and — when the sheet is being synced — encrypt +
  // broadcast the op to connected peers. A sheet is "under sheetsync" once it has
  // a writers list or a crdt op-log (i.e. it was sealed / shared / committed
  // before). 元 and ordinary grids keep the plain path. The error surface is the
  // same (message under the editor, stay in the cell), so a gate/lock rejection
  // reads like a parse error.
  const seg = String(prior?.segment ?? (key.includes(".") ? key.slice(0, key.indexOf(".")) : "origin"));
  const ssCommit = resolveFn(state, "sheetsync.commit") as Fn | undefined;
  const synced = key !== "元" && !!ssCommit && (!!state.cels.get(`${seg}.crdt`) || !!state.cels.get(`${seg}.writers`));
  const surfaceErr = async (msg: string): Promise<State> => {
    await (resolveFn(state, "setValueBatch") as Fn)(state, [["元.error", msg], ["元.editing", key], ["sheet.editing", key]]);
    await (resolveFn(state, "drain") as Fn)(state, "dom.paint");
    return state;
  };
  if (synced && ssCommit) {
    let r: { ok?: boolean; error?: string };
    try { r = await ssCommit(state, seg, key, src) as { ok?: boolean; error?: string }; }
    catch (e) { r = { ok: false, error: String((e as { message?: unknown })?.message ?? e) }; }
    // sheetsync.commit already setCel'd the source, folded, and ran a cycle on
    // success; on failure (not a writer / locked / parse) surface + stay put.
    if (!r?.ok) return surfaceErr(String(r?.error ?? "rejected").replace(/^[a-z]+:\s*/, ""));
  } else {
    try {
      await setCel(state, key, { celType: spec.celType, f: spec.f, v: spec.v, metadata: md });
    } catch (e) {
      // A parse/compile error (e.g. `=sheets("in" 4 3)` — infix wants commas)
      // throws OUT of setCel, which would abort the commit before any paint —
      // so the cell looked like it did nothing. Surface the message under the
      // editor and stay in the cell so it can be fixed.
      const msg = String((e as { message?: unknown })?.message ?? e).replace(/^setCel:\s*"[^"]*"\s*—\s*/, "");
      return surfaceErr(msg);
    }
  }

  // SPARSE: a commit into an empty address just BIRTHED the cel — re-derive
  // the sheet's content formula so the grid renders + reacts to it.
  if (bornAddr) {
    const regrid = resolveFn(state, "sheetapp.regrid") as Fn | undefined;
    if (regrid) { try { await regrid(state, key.slice(0, key.indexOf("."))); } catch { /* best-effort */ } }
  }

  // keep the selection on the committed cell and refresh the bar's draft to its
  // (now re-evaluated) source; clear inline editing.
  await (resolveFn(state, "setValueBatch") as Fn)(state, [["元.editing", null], ["sheet.editing", null], ["元.error", null], ["元.selected", key], ["sheet.selected", key], ["元.draft", src], ["sheet.draft", src]]);
  // fire generators so they enqueue, then commit structure + sweep. Loop until
  // quiescent: a genesis effect can in turn materialize cels whose own formulas
  // are requests (e.g. a seeded grid cell holding =db(…)) — keep draining until
  // a pass adds nothing new (capped, so a runaway can't spin forever).
  const drain = resolveFn(state, "drain") as Fn;
  const gd = resolveFn(state, "genesis.drain") as Fn | undefined;
  const dd = resolveFn(state, "defn.drain") as Fn | undefined;
  for (let pass = 0; pass < 8; pass++) {
    const before = state.cels.size;
    await (resolveFn(state, "runCycle") as Fn)(state);
    for (const ch of ["genesis.commit", "defn.commit", "checkpoint.commit", "origin.effects"]) {
      if (state.cels.get(ch)) await drain(state, ch);
    }
    if (gd) await gd([], state);
    if (dd) await dd([], state);
    if (state.cels.size === before) break; // no new cels this pass → settled
  }
  await applyDeclaredGeom(state, key as string);
  // …rebuild the cell list (new grids in, swept cels out), re-fire, paint.
  await rewireView(state, cellKeys(state));
  await (resolveFn(state, "runCycle") as Fn)(state);
  // the rebuild's runCycle can re-fire request cels (a SPARSE-born cel may
  // only get its channel wiring on this pass) — land anything it enqueued.
  for (const ch of ["genesis.commit", "defn.commit", "checkpoint.commit", "origin.effects"]) {
    if (state.cels.get(ch)) await drain(state, ch);
  }
  // A RUNTIME error (the formula parsed but threw while evaluating — bad ref,
  // div-by-zero, a verb that raised) leaves an error VALUE on the cell that would
  // otherwise just render blank. Surface it under the editor + stay in the cell,
  // the same as a parse error.
  const cv = state.cels.get(key)?.v as { kind?: string; message?: string } | undefined;
  if (cv && typeof cv === "object" && cv.kind === "error") {
    await (resolveFn(state, "setValueBatch") as Fn)(state, [["元.error", "#ERROR: " + String(cv.message ?? "evaluation failed")], ["元.editing", key], ["sheet.editing", key]]);
  }
  await drain(state, "dom.paint");
  return state;
};

// neighbour of a grid cell key (<seg>.<col><row>) in a direction, IF it is
// addressable (so navigation never lands off the sheet). dr/dc step row/col.
// SPARSE: the neighbour usually has no backing cel yet — an address counts
// when the cel exists OR it falls inside the sheet's rendered range
// (`<seg>.dims`); the grid renders synthesized cells there, so selecting /
// editing an unborn address is exactly how sparse cells are born.
const neighbourCell = (state: State, key: string, dr: number, dc: number): string | null => {
  const dot = key.lastIndexOf("."); if (dot < 0) return null;
  const seg = key.slice(0, dot), addr = key.slice(dot + 1);
  const m = /^([A-Z]+)(\d+)$/.exec(addr); if (!m) return null;
  const colN = [...m[1]].reduce((n, ch) => n * 26 + (ch.charCodeAt(0) - 64), 0) + dc;
  const rowN = Number(m[2]) + dr;
  if (colN < 1 || rowN < 1) return null;
  let col = "", c = colN; while (c > 0) { col = String.fromCharCode(64 + ((c - 1) % 26) + 1) + col; c = Math.floor((c - 1) / 26); }
  const nk = `${seg}.${col}${rowN}`;
  if (state.cels.get(nk)) return nk;
  const dims = state.cels.get(`${seg}.dims`)?.v as { rows?: unknown; cols?: unknown } | undefined;
  if (dims && rowN <= (Number(dims.rows) || 0) && colN <= (Number(dims.cols) || 0)) return nk;
  return null;
};
const cellBelow = (state: State, key: string): string | null => neighbourCell(state, key, 1, 0);

// growNeighbour — the edge of the rendered range is not the edge of the sheet:
// when the neighbour address is valid but OUTSIDE `<seg>.dims`, grow dims
// (at-least semantics, like =addCells) and return the key. Arrow-past-the-edge
// extends the grid one row/col at a time — Excel's unbounded feel without
// rendering unused space up front. No dims cel (the 元 root, legacy) → null.
const growNeighbour = async (state: State, key: string, dr: number, dc: number): Promise<string | null> => {
  const dot = key.lastIndexOf("."); if (dot < 0) return null;
  const seg = key.slice(0, dot), addr = key.slice(dot + 1);
  const m = /^([A-Z]+)(\d+)$/.exec(addr); if (!m) return null;
  const colN = [...m[1]!].reduce((n, ch) => n * 26 + (ch.charCodeAt(0) - 64), 0) + dc;
  const rowN = Number(m[2]) + dr;
  if (colN < 1 || rowN < 1) return null;
  const dimsKey = `${seg}.dims`;
  const dims = state.cels.get(dimsKey)?.v as { rows?: unknown; cols?: unknown } | undefined;
  if (!dims) return null;
  const rows = Math.max(Number(dims.rows) || 0, rowN), cols = Math.max(Number(dims.cols) || 0, colN);
  if (rows === (Number(dims.rows) || 0) && cols === (Number(dims.cols) || 0)) return null;
  await (resolveFn(state, "setValue") as Fn)(state, dimsKey, { rows, cols });
  let col = "", c = colN; while (c > 0) { col = String.fromCharCode(64 + ((c - 1) % 26) + 1) + col; c = Math.floor((c - 1) / 26); }
  return `${seg}.${col}${rowN}`;
};

// Editor keys: Enter commits + moves DOWN; Shift+Enter inserts a newline; Tab /
// Shift+Tab indent / outdent at the cursor (a tab char) instead of moving
// focus. Multi-line + tabs make hand-written formulas readable (the parser
// ignores whitespace).
const key: Fn = async (state: State, payload: unknown, event: unknown) => {
  const e = event as {
    key?: string; shiftKey?: boolean; preventDefault?: () => void;
    target?: { value: string; selectionStart: number; selectionEnd: number };
  } | undefined;
  if (!e) return state;
  if (e.key === "Enter" && !e.shiftKey) {
    e.preventDefault?.();
    // Excel: Enter ENDS the edit session — blur the input first, or the
    // painter's focused-control guard (apply.ts writeAttr) will refuse to
    // update the formula bar onto the next cell and it keeps showing the
    // just-committed source.
    (e.target as { blur?: () => void } | undefined)?.blur?.();
    await commit(state, payload);
    // Excel: Enter commits, then the active cell moves DOWN one row (if that cell
    // exists in the grid). The selection move re-renders the bar onto the new cell.
    const below = cellBelow(state, String(payload ?? ""));
    if (below) await (resolveFn(state, "origin.select") as Fn)(state, below);
    return state;
  }
  if (e.key === "Tab") {
    e.preventDefault?.(); // don't move focus — indent in place
    const ta = e.target;
    if (ta && typeof ta.selectionStart === "number" && typeof ta.value === "string") {
      const s = ta.selectionStart, en = ta.selectionEnd, val = ta.value;
      let next = val, caret = s;
      if (e.shiftKey) { // outdent: drop a leading tab on the cursor's line
        const ls = val.lastIndexOf("\n", s - 1) + 1;
        if (val[ls] === "\t") { next = val.slice(0, ls) + val.slice(ls + 1); caret = Math.max(ls, s - 1); }
      } else { next = val.slice(0, s) + "\t" + val.slice(en); caret = s + 1; }
      ta.value = next; ta.selectionStart = ta.selectionEnd = caret;
      await (resolveFn(state, "setValue") as Fn)(state, "元.draft", next);
    }
  }
  // Shift+Enter falls through → the textarea inserts a newline itself.
  return state;
};

// gridkey — the GLOBAL keydown listener (document|keydown, installed by viewfire)
// that gives a SELECTED-but-not-editing cell Excel navigation. It only acts when a
// cell is selected, NOT being edited, and focus isn't already in a form control
// (so it never fights the formula bar / inline editor — those own their own keys).
//   • arrows / Tab        → move the selection to the neighbour cell (if it exists)
//   • Enter               → move the selection DOWN one row
//   • a printable key      → start editing the cell, seeding the draft with that
//                            char. The inline editor (autofocus) shows it with the
//                            cursor; the formula bar mirrors it (both bind 元.draft).
//   • Backspace / Delete  → start editing with an empty draft (clears on commit)
const PRINTABLE = /^[\x20-\x7e]$/;   // a single visible ASCII char (formula content)
const gridkey: Fn = async (state: State, _payload: unknown, event: unknown) => {
  const e = event as { key?: string; shiftKey?: boolean; ctrlKey?: boolean; metaKey?: boolean; altKey?: boolean; preventDefault?: () => void } | undefined;
  if (!e || !e.key) return state;
  // editing in progress → the inline editor / formula bar own the keys.
  if (state.cels.get("元.editing")?.v) return state;
  // focus already in an input/textarea/button → leave it alone.
  if (isFormControl(event)) return state;
  const sel = String(state.cels.get("元.selected")?.v ?? "");
  if (!sel) return state;

  const move = async (dr: number, dc: number) => {
    const k = neighbourCell(state, sel, dr, dc) ?? await growNeighbour(state, sel, dr, dc);
    if (k) { e.preventDefault?.(); await (resolveFn(state, "origin.select") as Fn)(state, k); }
  };
  switch (e.key) {
    case "ArrowUp":    await move(-1, 0); return state;
    case "ArrowDown":  await move(1, 0); return state;
    case "ArrowLeft":  await move(0, -1); return state;
    case "ArrowRight": await move(0, 1); return state;
    case "Tab":        await move(0, e.shiftKey ? -1 : 1); return state;
    case "Enter":      await move(1, 0); return state;
  }
  // type-to-edit: a printable key (no modifiers) opens the inline editor seeded with
  // that char; Backspace/Delete open it empty. The editor's autofocus + the painter's
  // focused-skip keep the cursor in the cell while the bar mirrors the draft.
  const printable = !e.ctrlKey && !e.metaKey && !e.altKey && PRINTABLE.test(e.key);
  const clearing = e.key === "Backspace" || e.key === "Delete";
  if (printable || clearing) {
    e.preventDefault?.();
    const seed = printable ? e.key : "";
    await (resolveFn(state, "setValueBatch") as Fn)(state,
      [["元.editing", sel], ["sheet.editing", sel], ["元.draft", seed], ["sheet.draft", seed], ["元.error", null]]);
    await (resolveFn(state, "runCycle") as Fn)(state);
    await (resolveFn(state, "drain") as Fn)(state, "dom.paint");
  }
  return state;
};

// ── persistence — save the sheet as a FILE in OPFS (no localStorage) ─────────
// A "sheet archive" is just the cell SOURCES (元.cells) + any def'd functions.
// Replaying them reconstructs the sheet (grids regenerate, values + formulas
// come back). =save()/=open() round-trip it through /plastron/sheets/<name>.json
// so saved sheets are real, discoverable files; =link() is the no-filesystem path.

const collectArchive = (state: State): { v: number; cells: [string, string][]; defs: [string, string, string][] } => {
  const keys = (state.cels.get("元.cells")?.v as string[] | undefined) ?? ["元"];
  const cells: [string, string][] = [];
  // the view scan (cellKeys) pulls gen-2 window CHROME (win|wasm|desktop.<x>.state/
  // content/frame) into 元.cells; those are derived self-mounting windows, not user
  // data — skip them so an archive holds only grid/data cels (re-genesis rebuilds
  // the windows). Archiving them re-commits a frame formula on restore (which mis-
  // fires window.raise on a bare "win" ref) and never round-trips cleanly.
  const CHROME = /^(?:win|wasm|desktop)\./;
  for (const k of keys) { if (CHROME.test(k)) continue; const s = cellSource(state, k); if (s !== "" && s !== README) cells.push([k, s]); }
  const defs: [string, string, string][] = [];
  for (const [k, c] of state.cels) {
    if (c.celType === "EditableLambdaCel" && c.metadata.segment === "origin") {
      const f = (c as { f?: string }).f;
      if (f) defs.push([k, String((c.metadata as { kind?: unknown }).kind ?? "js"), f]);
    }
  }
  return { v: 1, cells, defs };
};

// serialize the whole document to a single recreating formula source. Grids →
// cels("seg", r, c, at(addr, src)…); defs → def(…). One grid alone stays a
// bare cels(…); anything composite wraps in segment(…).
// Quote a string for re-serialized formula source (=seed/=link/save). Prefer the
// delimiter that needs NO escaping: if the content has " but not ', wrap in ' (so
// a nested formula like =dom("h1","x") dehydrates clean). Else default to ".
const qstr = (s: string): string =>
  (s.includes('"') && !s.includes("'"))
    ? "'" + s.replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'"
    : '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
const gridDims = (addrs: string[]): { r: number; c: number } => {
  let r = 1, c = 1;
  for (const a of addrs) {
    const m = /^([A-Za-z]+)(\d+)$/.exec(a);
    if (!m) continue;
    let col = 0; for (const ch of m[1]!.toUpperCase()) col = col * 26 + (ch.charCodeAt(0) - 64);
    r = Math.max(r, parseInt(m[2]!, 10)); c = Math.max(c, col);
  }
  return { r, c };
};
const buildSeed = (state: State): string => {
  const arch = collectArchive(state);
  const grids = new Map<string, [string, string][]>();
  for (const [key, src] of arch.cells) {
    if (key === "元" || /^=?\s*seed\s*\(/.test(src)) continue;   // skip 元 + any =seed() cell (no self-capture)
    const dot = key.indexOf(".");
    if (dot < 0) continue;   // grid cels only (seg.addr); no base cels anymore
    const seg = key.slice(0, dot), addr = key.slice(dot + 1);
    (grids.get(seg) ?? grids.set(seg, []).get(seg)!).push([addr, src]);
  }
  const parts: string[] = [];
  for (const [seg, cells] of grids) {
    const { r, c } = gridDims(cells.map(([a]) => a));
    const ats = cells.filter(([, s]) => s !== "").map(([a, s]) => `at(${qstr(a)}, ${qstr(s)})`);
    parts.push(`cels(${qstr(seg)}, ${r}, ${c}${ats.length ? ", " + ats.join(", ") : ""})`);
  }
  for (const [name, kind, f] of arch.defs) parts.push(`def(${qstr(name)}, ${qstr(kind)}, ${qstr(f)})`);
  if (parts.length === 0) return "=cels(1, 1)";
  if (parts.length === 1 && parts[0]!.startsWith("cels(")) return "=" + parts[0];
  return "=segment(" + parts.join(", ") + ")";
};

// segmentFormula(seg) — the minting FORMULA for ONE segment (the per-segment twin
// of buildSeed). A workbook → =cels(seg, r, c, at(…)); a def → =def(…). Returns ""
// for a segment with no formula form (e.g. a winapp window — use its archive).
const segmentFormula = (state: State, seg: string): string => {
  const arch = collectArchive(state);
  const cells = arch.cells
    .filter(([k]) => k.startsWith(seg + ".") && !/^=?\s*seed\s*\(/.test(k))
    .map(([k, s]) => [k.slice(seg.length + 1), s] as [string, string]);
  if (cells.length) {
    const { r, c } = gridDims(cells.map(([a]) => a));
    const ats = cells.filter(([, s]) => s !== "").map(([a, s]) => `at(${qstr(a)}, ${qstr(s)})`);
    return `=cels(${qstr(seg)}, ${r}, ${c}${ats.length ? ", " + ats.join(", ") : ""})`;
  }
  const def = arch.defs.find(([name]) => name === seg);
  if (def) return `=def(${qstr(def[0])}, ${qstr(def[1])}, ${qstr(def[2])})`;
  return "";
};

const restoreArchive = async (state: State, arch: { cells?: [string, string][]; defs?: [string, string, string][] }): Promise<void> => {
  const setCel = resolveFn(state, "setCel") as Fn;
  for (const [k, kind, f] of (arch.defs ?? [])) {
    await setCel(state, k, { celType: "EditableLambdaCel", f, metadata: { kind, segment: "origin", name: k } });
  }
  const setValue = resolveFn(state, "setValue") as Fn;
  for (const [k, src] of (arch.cells ?? [])) { await setValue(state, "元.draft", src); await commit(state, k); }
};

